-- Tres tipos de menú (p.ej. comida / bebidas / especiales); cada categoría pertenece a uno.
-- Los nombres son provisionales: se renombran desde el panel de administración cuando el
-- dueño defina los tres menús reales.

CREATE TABLE menus (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(100) NOT NULL,
    position INTEGER      NOT NULL DEFAULT 0
);

