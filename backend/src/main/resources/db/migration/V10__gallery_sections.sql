-- Las fotos del local pasan de una sola galería ("Así es el rancho") a varias secciones
-- administrables desde el panel (ej. "Así es el rancho", "Nuestros platillos", "Eventos"),
-- igual que los menús. Las fotos que ya existían quedan en una primera sección con ese mismo nombre.
CREATE TABLE gallery_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    name_en VARCHAR(100),
    name_fr VARCHAR(100),
    name_zh VARCHAR(100),
    position INT NOT NULL
);

INSERT INTO gallery_sections (name, position) VALUES ('Así es el rancho', 0);

ALTER TABLE gallery_photos ADD COLUMN section_id BIGINT;
UPDATE gallery_photos SET section_id = (SELECT id FROM gallery_sections WHERE name = 'Así es el rancho');
ALTER TABLE gallery_photos ALTER COLUMN section_id SET NOT NULL;
ALTER TABLE gallery_photos ADD CONSTRAINT fk_gallery_photos_section
    FOREIGN KEY (section_id) REFERENCES gallery_sections(id) ON DELETE CASCADE;
